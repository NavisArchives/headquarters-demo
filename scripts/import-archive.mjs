#!/usr/bin/env node
// The invoice archive (2023–2026) -> HQ. Three steps, three commands, never
// chained (HQ's database is live production):
//
//   node scripts/import-archive.mjs --check
//       Validates data/archive/invoices-2023-2026.json offline. Prints the
//       per-year and per-client summary and every problem and warning, and
//       checks that the committed SQL files match the JSON. Exits 1 on any
//       problem. Touches no database.
//
//   node scripts/import-archive.mjs --build
//       Regenerates data/archive/import-archive.sql and precheck-archive.sql
//       from the JSON (after an edit to the JSON). Touches no database.
//
// The database steps are plain wrangler commands Andy runs himself:
//   npx wrangler d1 execute hq --remote --file data/archive/precheck-archive.sql   (read-only)
//   npx wrangler d1 execute hq --remote --file data/archive/import-archive.sql     (the write)
// The import SQL is idempotent: an invoice number already in HQ is skipped
// with its lines and payments, so running it twice changes nothing.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import {
  validateArchive, summarizeArchive, buildImportStatements, buildPrecheckStatements, toSqlFile,
} from '../src/shared/archive-import.js';
import { BANK_ACCOUNT_DEFAULTS } from '../src/worker/db.js';

const DATA = new URL('../data/archive/invoices-2023-2026.json', import.meta.url);
const IMPORT_SQL = new URL('../data/archive/import-archive.sql', import.meta.url);
const PRECHECK_SQL = new URL('../data/archive/precheck-archive.sql', import.meta.url);

const euro = (c) => `${(c / 100).toLocaleString('fr-BE', { minimumFractionDigits: 2, maximumFractionDigits: 2 })} €`;
const pad = (s, n) => String(s).padEnd(n);
const padL = (s, n) => String(s).padStart(n);

export function renderFiles(data) {
  const defaults = BANK_ACCOUNT_DEFAULTS.filter((a) => a.id !== 'kbc');
  const importSql = toSqlFile(buildImportStatements(data, { defaultAccounts: defaults }), [
    'HQ invoice archive 2023-2026 - generated by scripts/import-archive.mjs --build from',
    'data/archive/invoices-2023-2026.json. Do not edit by hand; edit the JSON and rebuild.',
    'Needs migration 0019. Idempotent and additive: every INSERT is guarded by WHERE NOT EXISTS,',
    'an invoice number already in HQ is skipped (with its lines and payments), and the one UPDATE',
    'adds the KBC account to settings.bank_accounts only if it is missing.',
    'Run: npx wrangler d1 execute hq --remote --file data/archive/import-archive.sql',
  ]);
  const precheckSql = toSqlFile(buildPrecheckStatements(data), [
    'READ-ONLY look at HQ before the archive import - SELECTs only.',
    'Run: npx wrangler d1 execute hq --remote --file data/archive/precheck-archive.sql',
    'Shows: whether migration 0019 is applied, which archive numbers are already in HQ (skipped),',
    'which existing clients the archive will reuse, and the bank accounts setting.',
  ]);
  return { importSql, precheckSql };
}

function printSummary(data) {
  const { years } = summarizeArchive(data);
  console.log('\nINVOICE ARCHIVE - per year, per client (EUR)\n');
  for (const y of years) {
    console.log(`${y.year}  ${padL(y.count, 2)} invoices  invoiced ${padL(euro(y.invoiced_cents), 13)}  paid ${padL(euro(y.paid_cents), 13)}  not proven ${padL(euro(y.unproven_cents), 12)}${y.expenses_cents ? `  expenses ${euro(y.expenses_cents)}` : ''}`);
    for (const c of y.clients) {
      console.log(`      ${pad(c.name, 50)} ${padL(c.count, 2)}  ${padL(euro(c.invoiced_cents), 13)}  paid ${padL(euro(c.paid_cents), 13)}${c.unproven_cents ? `  not proven ${euro(c.unproven_cents)}` : ''}`);
    }
  }
  const all = years.reduce((s, y) => s + y.invoiced_cents, 0);
  console.log(`\nAll years: ${data.invoices.length} invoices, ${euro(all)} invoiced, ${data.clients.length} clients, ${data.expenses.length} expenses.`);
  console.log(`Excluded (never imported): ${data.excluded.map((e) => e.number).join(' · ')}`);
}

function main(argv) {
  const mode = argv.includes('--build') ? 'build' : argv.includes('--check') ? 'check' : null;
  if (!mode) {
    console.error('Usage: node scripts/import-archive.mjs --check | --build');
    return 2;
  }
  const data = JSON.parse(readFileSync(DATA, 'utf8'));
  const { problems, warnings } = validateArchive(data);
  const files = renderFiles(data);

  if (mode === 'build') {
    if (problems.length) {
      console.error(`Not built - ${problems.length} problem(s):\n${problems.map((p) => `  ✗ ${p}`).join('\n')}`);
      return 1;
    }
    writeFileSync(IMPORT_SQL, files.importSql);
    writeFileSync(PRECHECK_SQL, files.precheckSql);
    console.log('Wrote data/archive/import-archive.sql and data/archive/precheck-archive.sql');
    return 0;
  }

  printSummary(data);
  for (const [url, body, name] of [[IMPORT_SQL, files.importSql, 'import-archive.sql'], [PRECHECK_SQL, files.precheckSql, 'precheck-archive.sql']]) {
    if (!existsSync(url)) problems.push(`data/archive/${name} is missing - run --build`);
    else if (readFileSync(url, 'utf8') !== body) problems.push(`data/archive/${name} is out of date with the JSON - run --build`);
  }
  console.log(`\nWARNINGS (${warnings.length}) - recorded on purpose, for Andy to know:`);
  for (const w of warnings) console.log(`  ! ${w}`);
  console.log(`\nPROBLEMS (${problems.length}):`);
  for (const p of problems) console.log(`  ✗ ${p}`);
  if (!problems.length) console.log('  none - the archive is ready to import.');
  return problems.length ? 1 : 0;
}

if (import.meta.url === `file://${process.argv[1]}`) process.exitCode = main(process.argv.slice(2));
